def phrase(language: str, key: str, **values) -> str:
    return TEXT.get(language, TEXT["en"])[key].format(**values)


def subject_label(language: str, subject: str) -> str:
    return SUBJECT_LABELS.get(language, SUBJECT_LABELS["en"]).get(subject, subject.replace("_", " ").title())


def menu_segments(text: str, college: str):
    instructions = [('Press 1 for English.','en'),
                    ('हिंदी के लिए 2 दबाइए।','hi'),
                    ('ಕನ್ನಡಕ್ಕಾಗಿ 3 ಅನ್ನು ಒತ್ತಿ.','kn')]
    if text == phrase('en','choose_language',college=college):
        return [(f'Hello, this is an automated call from {college}.','en'),*instructions]
    if text == phrase('en','language_retry'):
        return instructions
    return None
